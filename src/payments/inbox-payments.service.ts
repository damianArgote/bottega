import { Injectable, NotFoundException } from '@nestjs/common';
import { z } from 'zod';
import type { SessionUser } from '../auth/auth.service.js';
import type { BusinessAccess } from '../auth/business-access.guard.js';
import {
  PaymentApprover,
  PaymentStatus,
  type Payment,
} from '../generated/prisma/client.js';
import {
  HumanRepliesService,
  type HumanReplyResult,
} from '../inbox/human-replies.service.js';
import { PrismaService } from '../prisma/prisma.service.js';
import { PaymentsService, paymentView } from './payments.service.js';

export const chargeBodySchema = z
  .object({
    /** Whole pesos. */
    amountArs: z.number().int().min(1).max(100_000_000),
    concept: z.string().trim().min(1).max(200),
    /** Generated by the web per charge: retries never charge twice. */
    clientId: z.uuid(),
  })
  .strict();

/**
 * Payments from the inbox (prompt 07c): a person sends a charge to the
 * conversation (same rules as a reply: window, clientId, taking it), sees
 * its payments, and marks one paid ("Marcar pagado", the only way a
 * transfer is confirmed). Scoped to the person's business: 404 otherwise.
 */
@Injectable()
export class InboxPaymentsService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly payments: PaymentsService,
    private readonly replies: HumanRepliesService,
  ) {}

  /**
   * Creates the charge with the default account and sends its text as the
   * person's reply. The same `clientId` never makes a second payment nor
   * sends twice.
   */
  async charge(
    access: BusinessAccess,
    user: SessionUser,
    conversationId: string,
    input: z.infer<typeof chargeBodySchema>,
  ): Promise<{
    payment: ReturnType<typeof paymentView>;
    message: HumanReplyResult;
  }> {
    const conversation = await this.conversation(access, conversationId);
    const key = `inbox:${input.clientId}`;
    const previous = await this.replies.replayOf(key, conversation.id);
    if (!previous) {
      await this.replies.assertCanReply(conversation, user);
    }
    const { payment, text } = await this.payments.create({
      conversationId: conversation.id,
      amountArs: input.amountArs,
      concept: input.concept,
      purpose: 'manual',
      idempotencyKey: key,
      requestedBy: 'person',
    });
    const message = await this.replies.send({
      conversation,
      text,
      idempotencyKey: key,
      author: user,
    });
    return { payment: paymentView(payment), message };
  }

  /** The conversation's payments, newest first. */
  async list(access: BusinessAccess, conversationId: string) {
    const conversation = await this.conversation(access, conversationId);
    const payments = await this.prisma.payment.findMany({
      where: { conversationId: conversation.id, businessId: access.businessId },
      orderBy: { createdAt: 'desc' },
    });
    return payments.map(paymentView);
  }

  /**
   * "Marcar pagado": a person confirms a payment that is not approved yet
   * (a transfer, or one left for review). Idempotent: an approved payment
   * stays as it was. Emits `payment.approved` once.
   */
  async markPaid(access: BusinessAccess, user: SessionUser, paymentId: string) {
    const payment = await this.prisma.$transaction(async (tx) => {
      const [locked] = await tx.$queryRaw<Array<{ id: string }>>`
        SELECT id FROM payment
        WHERE id = ${paymentId}::uuid AND business_id = ${access.businessId}::uuid
        FOR UPDATE`;
      if (!locked) {
        throw new NotFoundException('Payment not found');
      }
      const current: Payment = await tx.payment.findUniqueOrThrow({
        where: { id: locked.id },
      });
      if (current.status === PaymentStatus.APPROVED) {
        return current;
      }
      const updated = await tx.payment.update({
        where: { id: current.id },
        data: {
          status: PaymentStatus.APPROVED,
          approvedAt: new Date(),
          approvedBy: PaymentApprover.USER,
          approvedByUserId: user.id,
        },
      });
      await this.payments.emit(tx, 'payment.approved', updated);
      return updated;
    });
    return paymentView(payment);
  }

  private async conversation(access: BusinessAccess, conversationId: string) {
    const conversation = await this.prisma.conversation.findFirst({
      where: { id: conversationId, line: { businessId: access.businessId } },
      select: {
        id: true,
        lineId: true,
        activeContextId: true,
        windowExpiresAt: true,
        lastInboundAt: true,
        contact: { select: { waId: true } },
      },
    });
    if (!conversation) {
      throw new NotFoundException('Conversation not found');
    }
    return conversation;
  }
}
