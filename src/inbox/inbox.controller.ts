import {
  Body,
  Controller,
  Get,
  HttpCode,
  HttpStatus,
  Param,
  Post,
  Query,
  Res,
  UseGuards,
} from '@nestjs/common';
import type { Response } from 'express';
import { z } from 'zod';
import { parseOrBadRequest } from '../admin/admin.schemas.js';
import type { SessionUser } from '../auth/auth.service.js';
import {
  type BusinessAccess,
  BusinessAccessGuard,
  CurrentBusiness,
} from '../auth/business-access.guard.js';
import { CurrentUser, SessionGuard } from '../auth/session.guard.js';
import { TemplatesSyncScheduler } from '../templates/templates-sync.scheduler.js';
import {
  TEMPLATE_SYNC_INTERVAL_MS,
  TemplatesService,
} from '../templates/templates.service.js';
import { ConversationActionsService } from './conversation-actions.service.js';
import { REPLY_STATUS } from './human-replies.service.js';
import { InboxMessagesService } from './inbox-messages.service.js';
import { InboxQueriesService } from './inbox-queries.service.js';
import { InboxService } from './inbox.service.js';

const conversationIdSchema = z.uuid();
const takeBodySchema = z.object({ force: z.boolean().default(false) }).strict();
const listQuerySchema = z
  .object({
    view: z.enum(['mine', 'unassigned', 'pending', 'resolved']),
    lineId: z.uuid().optional(),
    q: z.string().trim().min(1).max(100).optional(),
    cursor: z.string().min(1).max(500).optional(),
  })
  .strict();
const changesQuerySchema = z
  .object({ cursor: z.string().min(1).max(500).optional() })
  .strict();
const replyBodySchema = z
  .object({
    body: z.string().trim().min(1).max(4096),
    /** Generated by the web per message: retries never send twice. */
    clientId: z.uuid(),
  })
  .strict();
const templateBodySchema = z
  .object({
    templateId: z.uuid(),
    /** One per variable, in the order GET /templates lists them. */
    values: z.array(z.string().max(1024)).max(50).default([]),
    /** Generated by the web per message: retries never send twice. */
    clientId: z.uuid(),
  })
  .strict();
const templatesQuerySchema = z.object({ lineId: z.uuid().optional() }).strict();
const messagesQuerySchema = z
  .object({
    before: z.string().optional(),
    after: z.string().optional(),
  })
  .strict();

/**
 * The inbox API, for the people of each business. Every route lives under
 * /inbox/businesses/:businessId and requires a session and a membership in
 * that business.
 */
@Controller('inbox/businesses/:businessId')
@UseGuards(SessionGuard, BusinessAccessGuard)
export class InboxController {
  constructor(
    private readonly inbox: InboxService,
    private readonly actions: ConversationActionsService,
    private readonly queries: InboxQueriesService,
    private readonly messagesService: InboxMessagesService,
    private readonly templates: TemplatesService,
    private readonly templatesSync: TemplatesSyncScheduler,
  ) {}

  /**
   * Body `{ body, clientId }`. 200 sent or replayed, 202 uncertain, 502
   * rejected by Meta; 409 `WINDOW_CLOSED` or `ALREADY_TAKEN` before sending.
   */
  @Post('conversations/:conversationId/messages')
  async reply(
    @CurrentBusiness() access: BusinessAccess,
    @CurrentUser() user: SessionUser,
    @Param('conversationId') id: string,
    @Body() body: unknown,
    @Res({ passthrough: true }) res: Response,
  ) {
    const input = parseOrBadRequest(replyBodySchema, body ?? {}, 'body');
    const result = await this.messagesService.reply(
      access,
      user,
      this.id(id),
      input,
    );
    res.status(REPLY_STATUS[result.outcome]);
    return result;
  }

  /**
   * Body `{ templateId, values[], clientId }`: an approved template, also
   * with the window closed. Same statuses as a reply, plus 400
   * `TEMPLATE_VALUES` and 409 `TEMPLATE_*` before sending.
   */
  @Post('conversations/:conversationId/templates')
  async sendTemplate(
    @CurrentBusiness() access: BusinessAccess,
    @CurrentUser() user: SessionUser,
    @Param('conversationId') id: string,
    @Body() body: unknown,
    @Res({ passthrough: true }) res: Response,
  ) {
    const input = parseOrBadRequest(templateBodySchema, body ?? {}, 'body');
    const result = await this.messagesService.sendTemplate(
      access,
      user,
      this.id(id),
      input,
    );
    res.status(REPLY_STATUS[result.outcome]);
    return result;
  }

  /** `?lineId=`: the business's templates (from the last sync with Meta). */
  @Get('templates')
  listTemplates(
    @CurrentBusiness() access: BusinessAccess,
    @Query() query: unknown,
  ) {
    const { lineId } = parseOrBadRequest(templatesQuerySchema, query, 'query');
    return this.templates.list(access.businessId, lineId);
  }

  /** Reads the templates from Meta now; 409 `NO_WHATSAPP_ACCOUNT`. */
  @Post('templates/sync')
  @HttpCode(HttpStatus.OK)
  async syncTemplates(@CurrentBusiness() access: BusinessAccess) {
    const result = await this.templates.sync(access.businessId);
    // Keeps the daily sync running if no business had an account before.
    this.templatesSync.schedule(TEMPLATE_SYNC_INTERVAL_MS);
    return result;
  }

  @Post('conversations/:conversationId/read')
  @HttpCode(HttpStatus.OK)
  read(
    @CurrentBusiness() access: BusinessAccess,
    @Param('conversationId') id: string,
  ) {
    return this.messagesService.read(access, this.id(id));
  }

  /** `?view=mine|unassigned|pending|resolved&lineId=&q=&cursor=`, 30 a page. */
  @Get('conversations')
  conversations(
    @CurrentBusiness() access: BusinessAccess,
    @CurrentUser() user: SessionUser,
    @Query() query: unknown,
  ) {
    return this.queries.list(
      access,
      user,
      parseOrBadRequest(listQuerySchema, query, 'query'),
    );
  }

  /** Conversations changed since `?cursor=` (polling); see InboxQueriesService.changes. */
  @Get('changes')
  changes(@CurrentBusiness() access: BusinessAccess, @Query() query: unknown) {
    const { cursor } = parseOrBadRequest(changesQuerySchema, query, 'query');
    return this.queries.changes(access, cursor);
  }

  /** `?before=<seq>` older, `?after=<seq>` newer, 50 a page. */
  @Get('conversations/:conversationId/messages')
  messages(
    @CurrentBusiness() access: BusinessAccess,
    @Param('conversationId') id: string,
    @Query() query: unknown,
  ) {
    return this.queries.messages(
      access,
      this.id(id),
      parseOrBadRequest(messagesQuerySchema, query, 'query'),
    );
  }

  @Get('lines')
  lines(@CurrentBusiness() access: BusinessAccess) {
    return this.queries.lines(access);
  }

  /** The business and the user's role in it. */
  @Get()
  business(@CurrentBusiness() access: BusinessAccess) {
    return this.inbox.business(access);
  }

  /** Body `{ force?: boolean }`; force takes it from someone else (OWNER). */
  @Post('conversations/:conversationId/take')
  @HttpCode(HttpStatus.OK)
  take(
    @CurrentBusiness() access: BusinessAccess,
    @CurrentUser() user: SessionUser,
    @Param('conversationId') id: string,
    @Body() body: unknown,
  ) {
    const { force } = parseOrBadRequest(takeBodySchema, body ?? {}, 'body');
    return this.actions.take(access, user, this.id(id), { force });
  }

  @Post('conversations/:conversationId/release')
  @HttpCode(HttpStatus.OK)
  release(
    @CurrentBusiness() access: BusinessAccess,
    @CurrentUser() user: SessionUser,
    @Param('conversationId') id: string,
  ) {
    return this.actions.release(access, user, this.id(id));
  }

  /** "Devolver al bot". */
  @Post('conversations/:conversationId/handback')
  @HttpCode(HttpStatus.OK)
  handBack(
    @CurrentBusiness() access: BusinessAccess,
    @CurrentUser() user: SessionUser,
    @Param('conversationId') id: string,
  ) {
    return this.actions.handBack(access, user, this.id(id));
  }

  @Post('conversations/:conversationId/resolve')
  @HttpCode(HttpStatus.OK)
  resolve(
    @CurrentBusiness() access: BusinessAccess,
    @CurrentUser() user: SessionUser,
    @Param('conversationId') id: string,
  ) {
    return this.actions.resolve(access, user, this.id(id));
  }

  private id(value: string): string {
    return parseOrBadRequest(conversationIdSchema, value, 'conversationId');
  }
}
